#!/usr/bin/env python3
"""Keep Remotion's list of sections in step with the videos/ folder.

    ./x sync            rewrite src/sections.generated.tsx
    ./x sync --check    exit 1 if it is out of date (for CI)

Every section that has a Remotion segment is listed with its beats.json and the components its
segments name. A component lives in a file of the same name in the section folder
(videos/<video>/<section>/<Component>.tsx) and is exported under that name.
"""

from __future__ import annotations

import json
import sys

from xcore.paths import ROOT, VIDEOS

OUT = ROOT / "src" / "sections.generated.tsx"
HEAD = """// GENERATED by tools/registry.py (./x sync). Do not edit: change beats.json and run it again.
import type { SectionEntry } from "@kit";
"""


def build() -> str:
    imports: list[str] = []
    entries: list[str] = []
    k = 0
    for beats in sorted(VIDEOS.glob("*/*/beats.json")):
        section = beats.parent
        data = json.loads(beats.read_text(encoding="utf-8"))
        comps = [s["component"] for s in data.get("segments", []) if s.get("engine") == "remotion" and s.get("component")]
        if not comps:
            continue
        video_cfg = section.parent / "video.json"
        fps = json.loads(video_cfg.read_text()).get("fps") if video_cfg.exists() else None
        rel = f"../videos/{section.parent.name}/{section.name}"
        missing = [c for c in comps if not (section / f"{c}.tsx").exists()]
        if missing:
            sys.exit(f"{section.relative_to(ROOT)}: beats.json names {missing} but there is no {missing[0]}.tsx "
                     f"(./x scaffold {section.parent.name}/{section.name} writes a starting point)")
        names = []
        for c in comps:
            alias = f"C{k}_{c}"
            imports.append(f'import {{ {c} as {alias} }} from "{rel}/{c}";')
            names.append(f"{c}: {alias}")
        imports.append(f'import beats{k} from "{rel}/beats.json";')
        fps_part = f" fps: {int(fps)}," if fps else ""
        entries.append(
            f'  {{ key: "{section.parent.name}/{section.name}",{fps_part} beats: beats{k} as unknown as SectionEntry["beats"], '
            f"components: {{ {', '.join(names)} }} }},"
        )
        k += 1
    body = "\n".join(imports) + "\n\nexport const SECTIONS: SectionEntry[] = [\n" + "\n".join(entries) + "\n];\n"
    return HEAD + body


def main() -> None:
    text = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit("src/sections.generated.tsx is out of date: run ./x sync")
        print("REGISTRY OK")
        return
    if not OUT.exists() or OUT.read_text() != text:
        OUT.write_text(text)
        print(f"REGISTRY: wrote {OUT.relative_to(ROOT)}")
    else:
        print("REGISTRY: up to date")


if __name__ == "__main__":
    main()
